#!/usr/bin/env python3
"""Build the theme's brand assets from the local brand pack.

The brand pack lives in ./brand (copied from the client's "OUTRUN" folder). It is not in git
because the PDFs are confidential, so everything the theme needs is derived here and the
outputs are committed.

Outputs
  theme/assets/chakra-petch-{300,400,500,600,700}.woff2   Latin subset (no Thai)
  theme/assets/changa-arabic.woff2                        Arabic subset, variable wght 200-800
  theme/snippets/font-faces.liquid                        @font-face rules + preloads
  theme/snippets/logo.liquid                              horizontal logo, currentColor
  theme/snippets/logo-outline.liquid                      horizontal outline logo, currentColor
  theme/snippets/logo-symbol.liquid                       symbol, currentColor
  theme/assets/favicon.svg                                symbol on Deep Navy
  theme/assets/apple-touch-icon.png                       180x180, from the social profile image
  store-files/og-share-image.jpg                          upload in Online Store > Preferences
  docs/licenses/*-OFL.txt                                 font licenses (OFL 1.1)

Usage (from the repo root)
  python3 -m venv .venv
  .venv/bin/pip install -r tools/requirements.txt
  .venv/bin/python tools/build-brand-assets.py
"""

from __future__ import annotations

import math
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

from fontTools import subset
from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
BRAND = ROOT / "brand"
FONTS = BRAND / "Fonts and Colors" / "Fonts"
LOGOS = BRAND / "Logo Pack"
THEME = ROOT / "theme"
ASSETS = THEME / "assets"
SNIPPETS = THEME / "snippets"
STORE_FILES = ROOT / "store-files"
LICENSES = ROOT / "docs" / "licenses"

NAVY = "#0A1E2E"
CLOUD = "#F7FAFC"
GENERATED = "Generated by tools/build-brand-assets.py. Edit the script, not this file."

# Latin, Latin-1, Latin Extended-A, punctuation, currency, arrows, a few math signs.
# Chakra Petch's Thai and Vietnamese glyphs are dropped.
LATIN_RANGE = (
    "U+0000-00FF, U+0100-017F, U+0192, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, "
    "U+0329, U+2000-206F, U+20A0-20CF, U+2122, U+2190-2199, U+2212, U+2215, U+2260, "
    "U+2264-2265, U+FEFF, U+FFFD"
)
# Same blocks Google Fonts uses for its "arabic" subset. Also used as the CSS unicode-range,
# so English pages never download Changa.
ARABIC_RANGE = (
    "U+0600-06FF, U+0750-077F, U+0870-08FF, U+200C-200F, U+2010-2011, U+204F, U+25CC, "
    "U+2E41, U+FB50-FDFF, U+FE70-FEFF"
)

CHAKRA_WEIGHTS = {300: "Light", 400: "Regular", 500: "Medium", 600: "SemiBold", 700: "Bold"}

# Preloaded on every page: headings (600) + body. Body weight is the Q5 decision in
# docs/00-discovery.md: Chakra Petch 400 for English body, Changa for Arabic.
PRELOAD_HEADING = 600
PRELOAD_BODY = 400


def kb(path: Path) -> str:
    return f"{path.stat().st_size / 1024:.1f} KB"


# --------------------------------------------------------------------------- fonts


def subset_font(src: Path, dest: Path, unicodes: str) -> None:
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]  # keep copyright + OFL license strings
    opts.hinting = False
    opts.notdef_outline = True
    font = subset.load_font(str(src), opts)
    subsetter = subset.Subsetter(opts)
    subsetter.populate(unicodes=subset.parse_unicodes(unicodes.replace(" ", "")))
    subsetter.subset(font)
    subset.save_font(font, str(dest), opts)
    print(f"  {dest.relative_to(ROOT)}  {kb(src)} TTF -> {kb(dest)}")


def build_fonts() -> None:
    print("Fonts")
    chakra = FONTS / "Chakra Petch (English)"
    changa = FONTS / "Changa (Arabic)"
    for weight, style in CHAKRA_WEIGHTS.items():
        subset_font(chakra / f"ChakraPetch-{style}.ttf", ASSETS / f"chakra-petch-{weight}.woff2", LATIN_RANGE)
    subset_font(changa / "Changa-Variable.ttf", ASSETS / "changa-arabic.woff2", ARABIC_RANGE)

    LICENSES.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(chakra / "OFL.txt", LICENSES / "ChakraPetch-OFL.txt")
    shutil.copyfile(changa / "OFL.txt", LICENSES / "Changa-OFL.txt")

    faces = "\n".join(
        f'  @font-face {{ font-family: "Chakra Petch"; font-style: normal; font-weight: {w}; '
        f"font-display: swap;\n    src: url({{{{ 'chakra-petch-{w}.woff2' | asset_url }}}}) format(\"woff2\"); }}"
        for w in CHAKRA_WEIGHTS
    )
    snippet = f"""{{% doc %}}
  Self-hosted brand fonts: @font-face rules plus preloads. Render once inside <head>.

  - Chakra Petch (300-700) covers all Latin text, in English and in Arabic pages.
  - Changa (variable, wght 200-800) only covers Arabic characters (unicode-range), so English
    pages never download it. Use one stack everywhere and the browser picks per character:
    font-family: "Chakra Petch", "Changa", "Segoe UI", system-ui, sans-serif;
  - Shopify's font library can't be used: it has no Changa and no Arabic glyphs.

  {GENERATED}
{{% enddoc %}}
{{%- liquid
  assign lang = request.locale.iso_code | slice: 0, 2
-%}}
{{{{ 'chakra-petch-{PRELOAD_HEADING}.woff2' | asset_url | preload_tag: as: 'font', type: 'font/woff2', crossorigin: true }}}}
{{%- if lang == 'ar' %}}
{{{{ 'changa-arabic.woff2' | asset_url | preload_tag: as: 'font', type: 'font/woff2', crossorigin: true }}}}
{{%- else %}}
{{{{ 'chakra-petch-{PRELOAD_BODY}.woff2' | asset_url | preload_tag: as: 'font', type: 'font/woff2', crossorigin: true }}}}
{{%- endif %}}
<style>
{faces}
  @font-face {{ font-family: "Changa"; font-style: normal; font-weight: 200 800; font-display: swap;
    src: url({{{{ 'changa-arabic.woff2' | asset_url }}}}) format("woff2");
    unicode-range: {ARABIC_RANGE}; }}
</style>
"""
    (SNIPPETS / "font-faces.liquid").write_text(snippet, encoding="utf-8")
    print(f"  theme/snippets/font-faces.liquid")


# --------------------------------------------------------------------------- logos

SVG_NS = {"svg": "http://www.w3.org/2000/svg"}


def compact_path(d: str) -> str:
    """Round coordinates to 1 decimal (0.01px at header size) and drop trailing zeros."""

    def fmt(m: re.Match) -> str:
        s = f"{float(m.group()):.1f}".rstrip("0").rstrip(".")
        return "0" if s == "-0" else s

    return re.sub(r"-?\d+\.\d+", fmt, d)


def path_bounds(d: str) -> tuple[int, int, int, int]:
    pen = BoundsPen(None)
    parse_path(d, pen)
    x0, y0, x1, y1 = pen.bounds
    x0, y0 = math.floor(x0), math.floor(y0)
    return x0, y0, math.ceil(x1) - x0, math.ceil(y1) - y0


def read_logo(rel: str) -> tuple[str, dict, dict | None]:
    """Return (path d, attributes of the drawn path, attributes of the clip path or None)."""
    root = ET.parse(LOGOS / rel).getroot()
    clip = root.find(".//svg:clipPath/svg:path", SVG_NS)
    drawn = [p for p in root.findall(".//svg:path", SVG_NS) if p is not clip][0]
    return drawn.get("d"), dict(drawn.attrib), (dict(clip.attrib) if clip is not None else None)


def logo_snippet(name: str, source: str, description: str, *, outline: bool) -> str:
    d, attrs, clip = read_logo(source)
    x, y, w, h = path_bounds(d)
    d = compact_path(d)
    if outline:
        clip_id = f"{name}-clip"
        body = (
            f'<defs><clipPath id="{clip_id}"><path d="{d}" clip-rule="{clip.get("clip-rule", "evenodd")}"/>'
            f'</clipPath></defs><path d="{d}" fill="none" stroke="currentColor" '
            f'stroke-width="{attrs.get("stroke-width", "20")}" clip-path="url(#{clip_id})"/>'
        )
    else:
        body = f'<path d="{d}" fill="currentColor" fill-rule="{attrs.get("fill-rule", "evenodd")}"/>'
    return f"""{{% doc %}}
  {description}
  Official artwork from the Logo Pack ({source.split('/')[0]}), drawn in currentColor:
  set the color with CSS `color` and the size with CSS `height` (keep `width: auto`).
  Brand rules: minimum width 120px (logo) / 32px (symbol), dark on light or light on dark only.

  {GENERATED}

  @param {{string}} [class] - CSS class on the <svg>
  @param {{boolean}} [decorative] - true hides it from assistive tech (e.g. inside a link that has its own label)
  @param {{string}} [label] - accessible name; defaults to the shop name
{{% enddoc %}}
<svg class="{{{{ class }}}}" xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}" width="{w}" height="{h}" focusable="false"
  {{%- if decorative %}} aria-hidden="true"{{% else %}} role="img" aria-label="{{{{ label | default: shop.name | escape }}}}"{{% endif -%}}
>{body}</svg>
"""


def build_logos() -> None:
    print("Logos")
    logos = {
        "logo": ("01_Primary_Horizontal/SVG/OUTRUN_Horizontal_DeepNavy.svg",
                 "Primary horizontal logo (symbol + wordmark + ©). Header, mobile menu, password page.", False),
        "logo-outline": ("01_Primary_Horizontal/SVG/OUTRUN_Horizontal_Outline_CloudWhite.svg",
                         "Outline horizontal logo. Footer watermark (decorative).", True),
        "logo-symbol": ("04_Symbol/SVG/OUTRUN_Symbol_DeepNavy.svg",
                        "Symbol only. Small marks, 3D cap emblem, loading states.", False),
    }
    for name, (source, description, outline) in logos.items():
        out = SNIPPETS / f"{name}.liquid"
        out.write_text(logo_snippet(name, source, description, outline=outline), encoding="utf-8")
        print(f"  {out.relative_to(ROOT)}  {kb(out)}")

    # Favicon: the solid symbol at ~70% width, Cloud White on a Deep Navy square.
    d, attrs, _ = read_logo("04_Symbol/SVG/OUTRUN_Symbol_DeepNavy.svg")
    x, y, w, h = path_bounds(d)
    size, target = 64, 44
    s = target / w
    tx, ty = (size - w * s) / 2 - x * s, (size - h * s) / 2 - y * s
    favicon = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
        f'<rect width="{size}" height="{size}" fill="{NAVY}"/>'
        f'<path transform="translate({tx:.2f} {ty:.2f}) scale({s:.5f})" d="{compact_path(d)}" '
        f'fill="{CLOUD}" fill-rule="{attrs.get("fill-rule", "evenodd")}"/></svg>\n'
    )
    (ASSETS / "favicon.svg").write_text(favicon, encoding="utf-8")
    print(f"  theme/assets/favicon.svg  {kb(ASSETS / 'favicon.svg')}")


# --------------------------------------------------------------------------- images


def build_images() -> None:
    print("Images")
    social = BRAND / "Applications" / "Social_Media"

    # Apple touch icon: the profile symbol image (symbol on the navy gradient), cropped so
    # the symbol fills ~60% of the tile instead of ~42%.
    with Image.open(social / "Facebook_Profile_Symbol_2048x2048.png") as im:
        im = im.convert("RGB")
        side = round(im.width * 0.70)
        left = (im.width - side) // 2
        icon = im.crop((left, left, left + side, left + side)).resize((180, 180), Image.LANCZOS)
        icon.save(ASSETS / "apple-touch-icon.png", optimize=True)
    print(f"  theme/assets/apple-touch-icon.png  {kb(ASSETS / 'apple-touch-icon.png')}")

    # Default social share image. 1640x624 is wider than the 1.91:1 that Facebook/X show, so
    # platforms will crop the sides; a real 1200x630 export from the designer is better.
    STORE_FILES.mkdir(parents=True, exist_ok=True)
    with Image.open(social / "Facebook_Cover_1640x624.png") as im:
        im.convert("RGB").save(STORE_FILES / "og-share-image.jpg", quality=84, optimize=True, progressive=True)
    print(f"  store-files/og-share-image.jpg  {kb(STORE_FILES / 'og-share-image.jpg')}")


def main() -> int:
    if not FONTS.is_dir() or not LOGOS.is_dir():
        print(f"Brand pack not found at {BRAND}. Copy the client's OUTRUN folder there.", file=sys.stderr)
        return 1
    ASSETS.mkdir(parents=True, exist_ok=True)
    SNIPPETS.mkdir(parents=True, exist_ok=True)
    build_fonts()
    build_logos()
    build_images()
    return 0


if __name__ == "__main__":
    sys.exit(main())
